var FAN_TIERS = [88, 64, 48, 32, 24, 16, 12, 8, 6, 4, 2, 1];

// 按番数分组
function getRulesByFan() {
    var grouped = {};
    for (var i = 0; i < FAN_TIERS.length; i++) {
        grouped[FAN_TIERS[i]] = [];
    }
    for (var j = 0; j < RULES.length; j++) {
        var rule = RULES[j];
        if (grouped[rule.fan]) {
            grouped[rule.fan].push(rule);
        }
    }
    return grouped;
}

// 按名称查找规则
function getRuleByName(name) {
    for (var i = 0; i < RULES.length; i++) {
        if (RULES[i].name === name) return RULES[i];
    }
    return null;
}

module.exports = {
    RULES: RULES,
    FAN_TIERS: FAN_TIERS,
    getRulesByFan: getRulesByFan,
    getRuleByName: getRuleByName
};
